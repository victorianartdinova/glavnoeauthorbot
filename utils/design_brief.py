def extract_key_info_for_brief(post: str) -> Dict[str, Any]:
    """
    Извлечение ключевой информации из поста для ТЗ

    Returns:
        {
            "hook": str,
            "cta": str,
            "price_info": str,
            "location": str,
            "features": List[str]
        }
    """
    import re

    result = {
        "hook": "",
        "cta": "",
        "price_info": "",
        "location": "",
        "features": []
    }

    lines = post.split('\n')

    # Хук — первая непустая строка
    for line in lines:
        line = line.strip()
        if line and len(line) > 5:
            result["hook"] = line
            break

    # CTA — ищем ⚪️ или "Напишите"
    for line in lines:
        if '⚪️' in line or 'напишите' in line.lower() or 'пишите' in line.lower():
            result["cta"] = line.strip()
            break

    # Цена — ищем ₽ или руб
    price_pattern = r'[\d\s,]+\s*(?:₽|руб|млн|тыс)'
    for line in lines:
        match = re.search(price_pattern, line, re.IGNORECASE)
        if match:
            result["price_info"] = line.strip()
            break

    # Локация — ищем минут/мин или 📍
    for line in lines:
        if '📍' in line or 'минут' in line.lower() or 'мин.' in line.lower():
            result["location"] = line.strip()
            break

    # Фичи — строки с буллетами
    for line in lines:
        if line.strip().startswith(('•', '▪️', '✓', '✔', '-')):
            result["features"].append(line.strip())

    return result
