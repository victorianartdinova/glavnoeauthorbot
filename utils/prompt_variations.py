def detect_investment_lot(text: str) -> bool:
    """Определяет, является ли лот инвестиционным/коммерческим (офисы, ритейл, апартаменты под сдачу)"""
    text_lower = text.lower()

    # Исключения — это жилая недвижимость, не инвестиции
    residential_keywords = [
        'бизнес-класс', 'премиум-класс', 'комфорт-класс', 'элит-класс',
        'квартир', 'жилой', 'жк ', 'новостройк', 'для жизни'
    ]

    # Если есть признаки жилья — это НЕ инвестиционный лот
    if any(kw in text_lower for kw in residential_keywords):
        return False

    # Явные признаки коммерции/инвестиций
    investment_keywords = [
        'офис', 'коммерч', 'бизнес-центр', 'бц ', ' бц,',
        'торгов', 'ритейл', 'склад', 'помещени', 'коворкинг',
        'апарт-отел', 'апартамент под сдач', 'доходн', 'окупаем',
        'класс а', 'класса а', 'арендатор', 'арендный бизнес'
    ]

    return any(kw in text_lower for kw in investment_keywords)

