"""
Вариативность структур и формулировок для генерации контента
"""
import random
from collections import deque
from typing import List, Any

# История последних использованных вариантов (для избежания повторов)
_usage_history = {
    "structure": deque(maxlen=3),  # помним 3 последних структуры
    "hook": deque(maxlen=5),       # помним 5 последних хуков
    "style": deque(maxlen=4),      # помним 4 последних стиля
}


def _choose_avoiding_recent(items: List[Any], history_key: str) -> Any:
    """Выбрать случайный элемент, избегая недавно использованных"""
    history = _usage_history.get(history_key, deque())

    # Фильтруем недавно использованные
    available = [item for item in items if item not in history]

    # Если всё использовали — берём из полного списка
    if not available:
        available = items

    choice = random.choice(available)

    # Запоминаем выбор
    if history_key in _usage_history:
        _usage_history[history_key].append(choice)

    return choice


