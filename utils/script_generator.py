"""
Генератор сценариев для голосовых сообщений и кружков
"""
from typing import Literal
from utils.claude_api import generate_content


def generate_voice_script(
    topic: str,
    duration: Literal["short", "medium", "long"] = "medium",
    client_context: str = ""
) -> str:
    """
    Генерация сценария для голосового сообщения

    Args:
        topic: тема или текст поста для адаптации
        duration: "short" (45-60 сек), "medium" (60-90 сек), "long" (90-120 сек)
        client_context: контекст клиента

    Returns:
        Сценарий с таймкодами
    """
    duration_info = {
        "short": ("45-60 секунд", "~100-150 слов"),
        "medium": ("60-90 секунд", "~150-200 слов"),
        "long": ("90-120 секунд", "~200-250 слов")
    }

    time_range, word_range = duration_info.get(duration, duration_info["medium"])

    system_prompt = f"""Ты — сценарист для голосовых сообщений риэлтора/брокера.

ФОРМАТ: СЦЕНАРИЙ ГОЛОСОВОГО ({time_range})

СТРУКТУРА СЦЕНАРИЯ:

🎙 СЦЕНАРИЙ ГОЛОСОВОГО
📌 Тема: [название]
⏱ Хронометраж: {time_range} ({word_range})

═══════════════════════════════════════

[00:00-00:10] ХУК
🎯 Цель: зацепить внимание
📝 Текст (дословно):
"..."

💡 Интонация: [энергичная/спокойная/интригующая]

═══════════════════════════════════════

[00:10-00:40] ОСНОВНАЯ ЧАСТЬ
🎯 Цель: раскрыть тему
📝 Текст (дословно):
"..."

💡 Интонация: [экспертная/доверительная]
⏸ Паузы: [где сделать паузу для акцента]

═══════════════════════════════════════

[00:40-00:55] ВЫВОД + CTA
🎯 Цель: призыв к действию
📝 Текст (дословно):
"..."

💡 Интонация: [уверенная/дружелюбная]

═══════════════════════════════════════

📋 СУБТИТРЫ (короткие фразы для соцсетей):
• ...
• ...
• ...

🎬 ВАРИАНТЫ ХУКОВ (на выбор):
1. "..."
2. "..."

ПРАВИЛА:
- Текст должен звучать ЕСТЕСТВЕННО при озвучке
- Короткие предложения (5-10 слов)
- Разговорный стиль, не читай — говори
- Конкретные примеры и цифры
- НЕ используй сложные конструкции
- Субтитры — максимум 5-7 слов на фразу

{client_context}"""

    user_prompt = f"""Напиши сценарий голосового на тему:

{topic}

Длительность: {time_range}

Сделай сценарий готовым для записи — дословный текст с таймкодами."""

    return generate_content(system_prompt, user_prompt)


def generate_circle_script(
    topic: str,
    duration: Literal["short", "medium"] = "short",
    client_context: str = ""
) -> str:
    """
    Генерация сценария для видео-кружка

    Args:
        topic: тема или текст поста для адаптации
        duration: "short" (20-30 сек), "medium" (30-40 сек)
        client_context: контекст клиента

    Returns:
        Сценарий с визуальными подсказками
    """
    duration_info = {
        "short": ("20-30 секунд", "~50-80 слов"),
        "medium": ("30-40 секунд", "~80-100 слов")
    }

    time_range, word_range = duration_info.get(duration, duration_info["short"])

    system_prompt = f"""Ты — сценарист для видео-кружков в Telegram.

ФОРМАТ: СЦЕНАРИЙ КРУЖКА ({time_range})

СТРУКТУРА СЦЕНАРИЯ:

🎬 СЦЕНАРИЙ КРУЖКА
📌 Тема: [название]
⏱ Хронометраж: {time_range} ({word_range})

═══════════════════════════════════════

[00:00-00:05] ХУК
📝 Текст: "..."
👀 В кадре: [что делать — смотреть в камеру, показать жест]
💡 Энергия: [высокая/средняя]

═══════════════════════════════════════

[00:05-00:20] СУТЬ
📝 Текст: "..."
👀 В кадре: [жесты, направление взгляда]
⏸ Пауза: [где сделать для акцента]

═══════════════════════════════════════

[00:20-00:30] CTA
📝 Текст: "..."
👀 В кадре: [финальный жест — палец вверх, кивок]

═══════════════════════════════════════

📋 СУБТИТРЫ (для тех, кто смотрит без звука):
• ...
• ...
• ...

🎬 ВАРИАНТЫ ХУКОВ:
1. "..." [с жестом]
2. "..." [с интонацией]

📍 СОВЕТЫ ПО СЪЁМКЕ:
• Где снимать: [локация — офис/улица/объект]
• Освещение: [естественное/кольцевая лампа]
• Фон: [что должно быть видно]

ПРАВИЛА:
- Кружок = МАКСИМАЛЬНАЯ плотность информации
- Одна мысль = один кружок
- Говори как другу, не как на камеру
- Первые 3 секунды — решают всё
- Субтитры короткие (3-5 слов)

{client_context}"""

    user_prompt = f"""Напиши сценарий кружка на тему:

{topic}

Длительность: {time_range}

Сделай сценарий готовым для съёмки — текст + визуальные подсказки."""

    return generate_content(system_prompt, user_prompt)


def convert_post_to_script(
    post: str,
    script_type: Literal["voice", "circle"] = "voice",
    client_context: str = ""
) -> str:
    """
    Конвертация поста в сценарий

    Args:
        post: текст поста
        script_type: "voice" или "circle"
        client_context: контекст клиента

    Returns:
        Сценарий на основе поста
    """
    if script_type == "voice":
        return generate_voice_script(post, "medium", client_context)
    else:
        return generate_circle_script(post, "short", client_context)


def get_script_type_keyboard():
    """Клавиатура выбора типа сценария"""
    from aiogram.types import InlineKeyboardMarkup, InlineKeyboardButton

    return InlineKeyboardMarkup(inline_keyboard=[
        [InlineKeyboardButton(text="🎙 Голосовое (45-90 сек)", callback_data="script_voice")],
        [InlineKeyboardButton(text="⭕ Кружок (20-40 сек)", callback_data="script_circle")],
        [InlineKeyboardButton(text="⬅️ Назад", callback_data="script_back")]
    ])
