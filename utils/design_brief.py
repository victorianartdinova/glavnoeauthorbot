def generate_compact_brief(post: str, format_type: str = "banner", client_context: str = "") -> str:
    """
    Генерация КОМПАКТНОГО ТЗ дизайнеру (800-1200 символов)

    Args:
        post: текст поста
        format_type: "banner", "slider", "gallery", "carousel"
        client_context: контекст клиента (эмодзи и т.д.)

    Returns:
        Компактное ТЗ (8-12 буллетов)
    """
    format_names = {
        "banner": "Баннер (1 картинка)",
        "slider": "ГИФ-слайдер (2-3 кадра)",
        "gallery": "Галерея (4-5 карточек)",
        "carousel": "Карусель (5-8 карточек)"
    }

    system_prompt = f"""Ты — копирайтер. Создаёшь КОМПАКТНОЕ ТЗ для дизайнера.

ФОРМАТ: {format_names.get(format_type, "Баннер")}

ТРЕБОВАНИЯ К ТЗ:
- Максимум 8-12 пунктов
- Максимум 800-1200 символов
- Каждый пункт — одна строка
- Только КЛЮЧЕВАЯ информация

СТРУКТУРА:
• Формат: [тип креатива]
• Размер: [если известен]
• Текст на макете: [главный текст]
• Подтекст: [если есть]
• CTA: [кнопка/призыв]
• Визуал: [что показать]
• Настроение: [цвет/стиль]
• Референс: [если есть]
• Дедлайн: [если указан]

ЗАПРЕЩЕНО:
- Длинные описания
- Повторы
- Абстрактные пожелания
- Название ЖК и застройщика

{client_context}"""

    user_prompt = f"""Сделай КОМПАКТНОЕ ТЗ (максимум 12 пунктов) на основе поста:

{post}

Формат креатива: {format_names.get(format_type, "Баннер")}

Ответ — только буллеты, без вступлений."""

    return generate_content(system_prompt, user_prompt)


